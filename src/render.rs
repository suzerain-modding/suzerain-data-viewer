use crate::htmlgen::*;
use anyhow::{Context, Result, bail};
use indicatif::{MultiProgress, ProgressBar, ProgressStyle};
use indicatif_log_bridge::LogWrapper;
use log::info;
use serde_json::Value;
use simplelog::TermLogger;
use std::{
    fs::{self, read_dir, write},
    path::Path,
    time::Instant,
};

const MARKER: &str = ".sdv-output.json";

pub fn interactive() -> Result<()> {
    if Path::new("out").exists() {
        bail!("'out/' already exists. Choose another output with the html command.");
    }
    let chosen = select_json_file(find_json_files()?)?;
    run(Path::new(&chosen), Path::new("out"), false)
}

pub fn run(input: &Path, output: &Path, overwrite: bool) -> Result<()> {
    let old_files = if output.exists() {
        if !overwrite {
            bail!(
                "Output '{}' already exists; use a new directory or --overwrite.",
                output.display()
            );
        }
        if fs::symlink_metadata(output)?.file_type().is_symlink() || !output.is_dir() {
            bail!("HTML output must be a real directory.");
        }
        let marker = crate::index::read_json(&output.join(MARKER))
            .context("--overwrite requires a directory previously generated by this version of Data Viewer (missing/invalid .sdv-output.json)")?;
        if marker["generator"] != "suzerain_data_viewer" {
            bail!("Invalid HTML output marker.");
        }
        marker["files"]
            .as_array()
            .context("Invalid HTML output file list")?
            .iter()
            .map(|v| {
                v.as_str()
                    .map(str::to_owned)
                    .context("Invalid generated filename")
            })
            .collect::<Result<Vec<_>>>()?
    } else {
        Vec::new()
    };
    for name in &old_files {
        check_name(name)?;
    }
    let multi = MultiProgress::new();
    init_logger(&multi)?;
    let json = crate::index::read_json(input)?;
    let root_type = json["_type"]
        .as_str()
        .context("Expected root '_type' field")?;
    if !matches!(
        root_type,
        "<conversations Sordland>" | "<conversations Rizia>" | "<entity data>"
    ) {
        bail!(
            "Unsupported HTML root type '{root_type}'. Actor names remain available through the index."
        );
    }
    let parent = output
        .parent()
        .filter(|v| !v.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let temporary = parent.join(format!(".sdv-render-{}", crate::index::stamp()));
    fs::create_dir(&temporary)?;
    let start = Instant::now();
    let result = (|| -> Result<()> {
        write(
            temporary.join("style.css"),
            include_str!("../assets/style.css"),
        )?;
        write(
            temporary.join("script.js"),
            include_str!("../assets/script.js"),
        )?;
        route_root(&json, root_type, &multi, &temporary)?;
        let mut files = fs::read_dir(&temporary)?
            .map(|e| Ok(e?.file_name().to_string_lossy().into_owned()))
            .collect::<Result<Vec<_>>>()?;
        files.sort();
        for name in &files {
            check_name(name)?;
        }
        write(
            temporary.join(MARKER),
            serde_json::to_vec_pretty(
                &serde_json::json!({"generator":"suzerain_data_viewer","files":files}),
            )?,
        )?;
        if output.exists() {
            for name in old_files
                .iter()
                .chain(files.iter())
                .chain(std::iter::once(&MARKER.to_string()))
            {
                let target = output.join(name);
                if let Ok(meta) = fs::symlink_metadata(&target) {
                    if !meta.is_file() || meta.file_type().is_symlink() {
                        bail!("Refusing to replace non-file '{}'", target.display());
                    }
                    if !old_files.contains(name) && name != MARKER {
                        bail!(
                            "Output contains an unrelated file '{}'; it will not be overwritten.",
                            target.display()
                        );
                    }
                }
                if target.exists() && target.canonicalize()? == input.canonicalize()? {
                    bail!("HTML output must not replace the input dump.");
                }
            }
            for name in &files {
                fs::copy(temporary.join(name), output.join(name))?;
            }
            for name in &old_files {
                if !files.contains(name) && output.join(name).exists() {
                    fs::remove_file(output.join(name))?;
                }
            }
            fs::copy(temporary.join(MARKER), output.join(MARKER))?;
        } else {
            fs::rename(&temporary, output)?;
        }
        Ok(())
    })();
    // The temporary directory is created exclusively above and contains only generated flat files.
    if temporary.exists() {
        for entry in fs::read_dir(&temporary)? {
            fs::remove_file(entry?.path())?;
        }
        fs::remove_dir(&temporary)?;
    }
    result?;
    info!(
        "Done in {:.2?}. Open '{}' to browse.",
        start.elapsed(),
        output.join("index.html").display()
    );
    Ok(())
}

fn check_name(name: &str) -> Result<()> {
    let valid = matches!(name, "index.html" | "style.css" | "script.js")
        || name
            .strip_prefix("conversation")
            .and_then(|s| s.strip_suffix(".html"))
            .is_some_and(|s| s.parse::<i64>().is_ok())
        || matches!(
            name,
            "entity_allbillsdata.html"
                | "entity_allconversationsdata.html"
                | "entity_alldecisionsdata.html"
                | "entity_conditionalinstructiondata.html"
                | "entity_gameflowdata.html"
                | "entity_newsdata.html"
        );
    if !valid {
        bail!("Invalid generated filename in HTML output marker: '{name}'");
    }
    Ok(())
}

fn init_logger(multi: &MultiProgress) -> Result<()> {
    let log_level = log::LevelFilter::Info;
    let logger = TermLogger::new(
        log_level,
        simplelog::Config::default(),
        simplelog::TerminalMode::Mixed,
        simplelog::ColorChoice::Auto,
    );

    LogWrapper::new(multi.clone(), logger)
        .try_init()
        .context("Failed to initialize logger.")?;
    log::set_max_level(log_level);
    Ok(())
}

fn find_json_files() -> Result<Vec<String>> {
    let mut files: Vec<String> = read_dir(".")
        .context("Could not read current directory.")?
        .filter_map(|entry| {
            let entry = entry.ok()?;
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) == Some("json") {
                path.file_name().and_then(|n| n.to_str()).map(String::from)
            } else {
                None
            }
        })
        .collect();

    if files.is_empty() {
        bail!("No '.json' files found in the current directory.");
    }

    files.sort_unstable();
    Ok(files)
}

fn select_json_file(json_files: Vec<String>) -> Result<String> {
    inquire::Select::new("Select a JSON file to generate HTML for:", json_files)
        .prompt()
        .context("File selection cancelled.")
}

fn route_root(json: &Value, root_type: &str, multi: &MultiProgress, output: &Path) -> Result<()> {
    match root_type {
        "<conversations Sordland>" | "<conversations Rizia>" => {
            generate_conversations(json, root_type, multi, output)
        }
        "<entity data>" => generate_entity_data(json, root_type, multi, output),
        other => bail!("Unknown root type: '{other}'"),
    }
}

fn generate_conversations(
    json: &Value,
    root_type: &str,
    multi: &MultiProgress,
    output: &Path,
) -> Result<()> {
    let conversations = &json["conversations"];
    if !conversations.is_object() {
        bail!("Expected 'conversations' to be an object.");
    }

    let count = conversations
        .as_object()
        .map(|o| o.len().saturating_sub(1))
        .unwrap_or(0) as u64;

    info!("Generating index...");
    generate_conversations_index(conversations, root_type, output)
        .context("Failed to generate conversations index.")?;

    let progress = multi.add(make_progress_bar(count));
    progress.set_message(format!("Writing conversation pages ({root_type})"));

    info!("Generating conversation pages...");
    conversations_to_html_files(conversations, &progress, output)
        .context("Failed to generate conversation pages.")?;

    progress.finish_with_message("Finished writing conversation pages.");
    Ok(())
}

fn generate_entity_data(
    json: &Value,
    root_type: &str,
    multi: &MultiProgress,
    output: &Path,
) -> Result<()> {
    info!("Generating entity data pages...");

    let progress = multi.add(make_progress_bar(6));
    progress.set_message("Generating entity data...");

    generate_entity_data_files(json, &progress, root_type, output)
        .context("Failed to generate entity data pages.")?;

    progress.finish_with_message("Finished writing entity data pages.");
    Ok(())
}

fn make_progress_bar(len: u64) -> ProgressBar {
    let pb = ProgressBar::new(len);
    pb.set_style(
        ProgressStyle::with_template(
            "{spinner:.green} {msg} {bar:40.cyan/blue} {pos}/{len} ({eta})",
        )
        .unwrap()
        .progress_chars("#>-"),
    );
    pb
}
